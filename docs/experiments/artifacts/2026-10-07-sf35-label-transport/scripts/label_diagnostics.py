#!/usr/bin/env python3
"""SF-35 post-hoc label diagnostics (NOT pre-registered; changes no verdict).

Usage: label_diagnostics.py EXPORTS_ROOT [--out FILE.md] [--eps 10 15] [--grids 32 64 128 256]

Reads <root>/matrix_eps{E}/N{N}/{psi1,psi2}.npy (float64, shape (N+1, N, N), slab layout
idx = m3 + N (m2 + N j), x = m/N; psi1 = x2 + U1, psi2 = x3 + U2, U periodic in x2, x3).
python3 + numpy only.
  1. wrap check: max |U(next) - U| * N along x1 (np.diff), x2, x3 (np.roll, periodic).
  2. pointwise self-convergence psi(N) vs psi(2N)[::2,::2,::2]: max, RMS, per-plane max, orders.
  3. concentration of the non-convergence of c = grad psi1 x grad psi2 (2nd-order central
     differences, periodic in x2, x3, np.gradient-equivalent along x1), interior planes
     j = 1..N-1, c(N) vs c(2N) on common vertices, normalized by v_rms = RMS|c(2N)| over
     those vertices.
"""
import argparse
import os
import sys

import numpy as np

PLANES = (0.25, 0.5, 0.75, 1.0)


def load(root, eps, n, name):
    p = os.path.join(root, "matrix_eps%s" % eps, "N%d" % n, name + ".npy")
    if not os.path.exists(p):
        return None
    a = np.load(p, mmap_mode="r")
    if a.shape != (n + 1, n, n):
        raise SystemExit("bad shape %s for %s (expected %s)" % (a.shape, p, (n + 1, n, n)))
    return a


def periodic_part(psi, n, which):
    """U = psi - x2 (which=1) or psi - x3 (which=2), float64 (N+1, N, N)."""
    x = np.arange(n, dtype=np.float64) / n
    if which == 1:
        return np.asarray(psi) - x[None, :, None]
    return np.asarray(psi) - x[None, None, :]


def wrap_check(psi1, psi2, n):
    out = []
    for w, psi in ((1, psi1), (2, psi2)):
        u = periodic_part(psi, n, w)
        d1 = np.abs(np.diff(u, axis=0)).max() * n
        d2 = np.abs(np.roll(u, -1, axis=1) - u).max() * n
        d3 = np.abs(np.roll(u, -1, axis=2) - u).max() * n
        out.append((float(d1), float(d2), float(d3)))
    return out


def order(a, b):
    if not (np.isfinite(a) and np.isfinite(b)) or a <= 0 or b <= 0:
        return float("nan")
    return float(np.log2(a / b))


def selfconv(coarse, fine):
    """coarse (n+1,n,n), fine (2n+1,2n,2n)."""
    n = coarse.shape[1]
    f = np.asarray(fine[::2, ::2, ::2])
    d = np.abs(np.asarray(coarse) - f)
    planes = {xp: float(d[int(round(xp * n))].max()) for xp in PLANES}
    return dict(max=float(d.max()), rms=float(np.sqrt(np.mean(d * d))), planes=planes)


def cross(psi1, psi2, n):
    """c = grad psi1 x grad psi2 on interior planes 1..n-1 (n-1 planes), 3 components."""
    h = 1.0 / n

    def grad(p, which):
        # differentiate the periodic part U only (psi = x2 + U1 or x3 + U2), add the affine gradient back
        n_ = p.shape[1]
        p = periodic_part(p, n_, which)
        g1 = (p[2:] - p[:-2]) / (2 * h)
        q = p[1:-1]
        g2 = (np.roll(q, -1, axis=1) - np.roll(q, 1, axis=1)) / (2 * h)
        g3 = (np.roll(q, -1, axis=2) - np.roll(q, 1, axis=2)) / (2 * h)
        if which == 1:
            g2 = g2 + 1.0
        else:
            g3 = g3 + 1.0
        return g1, g2, g3

    a1, a2, a3 = grad(psi1, 1)
    b1, b2, b3 = grad(psi2, 2)
    return (a2 * b3 - a3 * b2, a3 * b1 - a1 * b3, a1 * b2 - a2 * b1)


def concentration(p1c, p2c, p1f, p2f, nc):
    """c(nc) vs c(2nc) on common vertices (coarse interior planes 1..nc-1)."""
    cc = cross(p1c, p2c, nc)
    cf = cross(p1f, p2f, 2 * nc)  # index i <-> fine plane i+1; common fine planes 2j -> index 2j-1
    sl = (slice(1, None, 2), slice(None, None, 2), slice(None, None, 2))
    cf = [c[sl] for c in cf]
    err2 = sum((a - b) ** 2 for a, b in zip(cc, cf))
    v2 = sum(b ** 2 for b in cf)
    vrms = float(np.sqrt(v2.mean()))
    del v2, cf, cc
    e = np.sqrt(err2).ravel() / vrms
    tot = float(np.sum(e * e))
    srt = np.sort(e)[::-1]
    cs = np.cumsum(srt * srt)
    k = int(np.searchsorted(cs, 0.5 * tot) + 1)
    j, m2, m3 = np.unravel_index(int(np.argmax(err2)), err2.shape)
    pct = {q: float(np.percentile(e, q)) for q in (50, 90, 99, 99.9)}
    return dict(rms=float(np.sqrt(np.mean(e * e))), pct=pct, emax=float(e.max()), nhalf=k,
                nvert=int(e.size), frac=k / e.size, vrms=vrms,
                loc=((j + 1) / nc, m2 / nc, m3 / nc))


def fmt(x):
    return "%.3e" % x


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("root")
    ap.add_argument("--out")
    ap.add_argument("--eps", nargs="*", default=["10", "15"])
    ap.add_argument("--grids", nargs="*", type=int, default=[32, 64, 128, 256])
    a = ap.parse_args()
    root = os.path.expanduser(a.root)
    L = []
    w = L.append
    w("# SF-35 post-hoc label diagnostics (NOT pre-registered)\n")
    w("Generated by `scripts/label_diagnostics.py` from the label exports under `%s`. Post-hoc exploratory checks: "
      "not part of the pre-registered thresholds A-H, they change no verdict. The eps 0.5 exports were lost on the "
      "mirror (rsync --delete sync), so eps 0.5 is not covered.\n" % a.root)
    for e in a.eps:
        eps_val = {"05": 0.5, "10": 1.0, "15": 1.5}.get(e, e)
        w("\n## eps = %s (`matrix_eps%s`)\n" % (eps_val, e))
        data = {}
        for n in a.grids:
            p1, p2 = load(root, e, n, "psi1"), load(root, e, n, "psi2")
            if p1 is None or p2 is None:
                w("- N=%d: exports missing, skipped" % n)
                continue
            data[n] = (p1, p2)
        w("\n### 1. Wrap check: max |U(next) - U| * N (a periodic-wrap defect would show ~1*N)\n")
        w("| N | U1 x1 | U1 x2 | U1 x3 | U2 x1 | U2 x2 | U2 x3 |")
        w("|---|---|---|---|---|---|---|")
        for n, (p1, p2) in data.items():
            r = wrap_check(p1, p2, n)
            w("| %d | %s |" % (n, " | ".join(fmt(v) for t in r for v in t)))
        w("\n### 2. Pointwise self-convergence psi(N) vs psi(2N)[::2,::2,::2]\n")
        w("| field | N->2N | max | RMS | max at x1=0.25 | 0.5 | 0.75 | 1.0 | order max | order RMS |")
        w("|---|---|---|---|---|---|---|---|---|---|")
        for fld in (0, 1):
            prev = None
            for n in a.grids:
                if n not in data or 2 * n not in data:
                    continue
                r = selfconv(data[n][fld], data[2 * n][fld])
                om = orr = float("nan")
                if prev is not None:
                    om, orr = order(prev["max"], r["max"]), order(prev["rms"], r["rms"])
                w("| psi%d | %d->%d | %s | %s | %s | %s | %s | %s | %.2f | %.2f |" % (
                    fld + 1, n, 2 * n, fmt(r["max"]), fmt(r["rms"]),
                    *[fmt(r["planes"][x]) for x in PLANES], om, orr))
                prev = r
        w("\n### 3. Concentration of the non-convergence of c = grad psi1 x grad psi2 (interior planes j=1..N-1)\n")
        w("Second-order central differences; c(N) vs c(2N) on common vertices; errors normalized by "
          "v_rms = RMS|c(2N)| over those vertices. N_half = number of vertices carrying half of the total squared "
          "error.\n")
        w("| pair | vertices | v_rms | RMS(err)/v_rms | p50 | p90 | p99 | p99.9 | max | N_half | frac_half | "
          "max at (x1,x2,x3) |")
        w("|---|---|---|---|---|---|---|---|---|---|---|---|")
        for n in a.grids:
            if n not in data or 2 * n not in data:
                continue
            r = concentration(data[n][0], data[n][1], data[2 * n][0], data[2 * n][1], n)
            w("| %d vs %d | %d | %s | %s | %s | %s | %s | %s | %s | %d | %.4f %% | (%.4f, %.4f, %.4f) |" % (
                n, 2 * n, r["nvert"], fmt(r["vrms"]), fmt(r["rms"]), fmt(r["pct"][50]), fmt(r["pct"][90]),
                fmt(r["pct"][99]), fmt(r["pct"][99.9]), fmt(r["emax"]), r["nhalf"], 100 * r["frac"], *r["loc"]))
            sys.stderr.write("eps %s N %d done\n" % (e, n))
    txt = "\n".join(L) + "\n"
    if a.out:
        with open(a.out, "w") as f:
            f.write(txt)
    else:
        sys.stdout.write(txt)


if __name__ == "__main__":
    main()
