#!/usr/bin/env python3
"""Per-phase device-memory digest of the SF-35 sigma^2 = 4 feasibility probes (J2).

Input: the nvidia-smi samples written by tools/probe_sf35/run.sh --memlog
(`nvidia-smi --query-gpu=memory.used --format=csv,noheader,nounits -lms 200`,
one integer MiB value per line, device-wide, includes the CUDA context) and the
TIMING line of the matching driver log (phase durations field / stage / trace /
diagnostics, in that order of execution).

Phase windows are reconstructed from the TIMING durations. The sampler is
started just before the driver and killed right after it exits, but its
period drifts from the nominal 200 ms (J2 512^3: 70981 samples over a
14241.5 s run), so sample i is placed at t = i * total / n_samples (effective
period). Windows are approximate to about one second.

Usage: memory_phases.py <raw/J2 directory>  (reads N256/N512 .mem.gz and .log)
"""
import gzip
import re
import sys
from pathlib import Path



def phases(log_text):
    m = re.search(r"^TIMING diagnostics=([0-9.]+)s field=([0-9.]+)s stage=([0-9.]+)s "
                  r"trace=([0-9.]+)s total=([0-9.]+)s", log_text, re.M)
    if not m:
        raise SystemExit("no TIMING line")
    diag, field, stage, trace, total = (float(x) for x in m.groups())
    t0 = 0.0
    out = [("field", t0, t0 + field)]
    t0 += field
    out.append(("stage", t0, t0 + stage))
    t0 += stage
    out.append(("trace", t0, t0 + trace))
    t0 += trace
    out.append(("diagnostics+export (remainder to total)", t0, total))
    return out, total


def main():
    d = Path(sys.argv[1])
    print("# Device memory by phase, J2 probes (nvidia-smi, 200 ms, device-wide, MiB)\n")
    print("Generated by `scripts/memory_phases.py raw/J2`. Phase windows from the driver TIMING line on the"
          " effective sample clock; approximate to ~1 s.\n")
    print("| N | phase | window [s] | max MiB | max GiB |")
    print("|---|---|---|---|---|")
    for n in (256, 512):
        vals = [int(x) for x in gzip.open(d / f"N{n}.mem.gz", "rt").read().split() if x.strip().isdigit()]
        ph, total = phases((d / f"N{n}.log").read_text())
        dt = total / len(vals)  # effective sample period (see module docstring)
        for name, a, b in ph:
            s = vals[int(a / dt):int(b / dt) + 1]
            mx = max(s) if s else float("nan")
            print(f"| {n} | {name} | {a:.0f}-{b:.0f} | {mx} | {mx / 1024:.2f} |")
        tr = [p for p in ph if p[0] == "trace"][0]
        body = vals[int((tr[1] + 10.0) / dt):int((tr[2] - 60.0) / dt)]
        if body:
            print(f"| {n} | trace body (window minus first 10 s and last 60 s; the end-of-run FD"
                  f" diagnostics fall in the last seconds) | {tr[1] + 10:.0f}-{tr[2] - 60:.0f} | {max(body)}"
                  f" | {max(body) / 1024:.2f} |")
        mx = max(vals)
        print(f"| {n} | **whole run** (argmax at {vals.index(mx) * dt:.1f} s, {len(vals)} samples,"
              f" effective period {dt * 1000:.1f} ms) | 0-{total:.0f}"
              f" | **{mx}** | **{mx / 1024:.2f}** |")
    n_cells = 512 ** 3
    mx512 = max(int(x) for x in gzip.open(d / "N512.mem.gz", "rt").read().split() if x.strip().isdigit())
    print(f"\nPeak per cell at 512^3: {mx512} MiB x 2^20 / 512^3 = {mx512 * 2**20 / n_cells:.1f} B/cell"
          " (includes the CUDA context; P2 temporaries freed).")


if __name__ == "__main__":
    main()
