"""Seed registry of addendum 1 (`seeds_registry_addendum.json`) and its checks.

The new blocks are the J9 block and EVERY reserve block (J9's own and those of the groups that reuse seeds); the paired reuse is declared
separately (J1/J8 on `g_s4`, J3 on `g_d_s1`, with their purpose).  `sf43plan.build.check_seeds` (frozen) runs on the frozen blocks and smoke
blocks plus the new blocks and must pass; every reuse range must lie inside the frozen block it pairs with and use the frozen Par2 transport rule.
"""
import json
import os
import re

from sf43plan import build as B

from .plan import ART, build_arms, jload, sha256_file, ART_REL

REGISTRY = os.path.join(ART, "seeds_registry_addendum.json")
FROZEN_REGISTRY = os.path.join(ART, "seeds_registry.json")


class SeedsError(ValueError):
    pass


def _block_of(frozen_blocks, first, last):
    return next((b for b in frozen_blocks if b["start"] <= first and last <= b["end"]), None)


def build_registry():
    """The registry dict generated from prereg_addendum.json and the frozen registry (no check yet)."""
    pre, fz = jload(os.path.join(ART, "prereg_addendum.json")), jload(os.path.join(ART, "seeds_registry.json"))
    arms = pre["arms"]
    new, reuse, groups = [], {}, {}
    for s in arms:
        first, last = s["seeds"]["start"], s["seeds"]["start"] + s["seeds"]["count"] - 1
        fb = _block_of(fz["blocks"], first, last)
        r = s["reserves"]
        if fb is None:           # new seeds: a block of its own, with its reserves
            new.append({"group": s["group"], "purpose": "%s: %d new realizations (%s)" % (s["id"], s["seeds"]["count"], s["origin"]), "start": first,
                        "count": s["seeds"]["count"], "end": last, "reserves": dict(r), "reserve_fraction": round(r["count"] / s["seeds"]["count"], 4),
                        "arms": [s["id"]]})
        else:                    # paired reuse: the seeds are declared below; the reserves are new seeds
            new.append({"group": s["group"], "purpose": "reserve seeds of %s (its seeds %d-%d are the paired reuse of %s)" % (s["id"], first, last, fb["group"]),
                        "start": r["start"], "count": r["count"], "end": r["start"] + r["count"] - 1,
                        "reserves": {"start": r["start"] + r["count"], "count": 0},   # none of its own: a zero-length span, ignored by the overlap test
                        "reserve_fraction": 0.0, "arms": [s["id"]], "reserve_only": True})
            e = reuse.setdefault((s["job"], fb["group"]), {"first": first, "last": last, "arms": [], "frozen_arms": fb["arms"]})
            e["first"], e["last"] = min(e["first"], first), max(e["last"], last)
            e["arms"].append(s["id"])
        groups[s["group"]] = r
    paired = []
    for (job, fg), e in reuse.items():
        run = {s["id"]: s["runner"] for s in arms}
        rule = ("frozen Par2 transport rule: field seed s uses transport.seed 420800001 + 1000 s, identical to the paired frozen arm (common random numbers)"
                if all(run[i] == "par2" for i in e["arms"]) else "consumer arms: no transport seed; paired by field seed only")
        paired.append({"id": "reuse_%s_%s" % (job, fg), "job": job, "arms": e["arms"], "first": e["first"], "last": e["last"], "pairs_with_group": fg,
                       "frozen_arms_of_group": e["frozen_arms"], "purpose": "paired contrast against the frozen arms of group %s on common seeds (common random numbers; "
                       "not a collision)" % fg, "transport": rule})
    return {"name": "sf43-addendum-1-seeds", "text": "Blocks NEW to the addendum plus the declared paired reuse of frozen blocks; generated by `python3 -m sf43add.camp "
            "check-seeds` from prereg_addendum.json; the check is sf43plan.build.check_seeds on the frozen registry's blocks plus these (disjointness, forbidden "
            "ranges, Par2 transport-seed overlap).", "frozen_registry": {"path": "%s/seeds_registry.json" % ART_REL, "sha256": sha256_file(os.path.join(ART, "seeds_registry.json"))},
            "blocks": new, "paired_reuse": sorted(paired, key=lambda x: x["id"])}


def check(reg):
    """Raise SeedsError unless the registry passes; returns the list of PASS lines."""
    fz = jload(os.path.join(ART, "seeds_registry.json"))
    merged = {k: fz[k] for k in ("forbidden_field_seeds", "forbidden_transport_seeds", "smoke_blocks")}
    merged["blocks"] = list(fz["blocks"]) + list(reg["blocks"])
    try:
        B.check_seeds(merged)
    except ValueError as e:
        raise SeedsError("check_seeds: %s" % e) from None
    out = ["PASS check_seeds: %d frozen + %d smoke + %d new blocks disjoint, outside the forbidden ranges, transport seeds disjoint"
           % (len(fz["blocks"]), len(fz["smoke_blocks"]), len(reg["blocks"]))]
    base = int(re.search(r"=\s*(\d+)\s*\+\s*1000", fz["par2_transport_rule"]).group(1))
    frozen_plan = jload(os.path.join(ART, "plan.json"))
    made, root = build_arms(frozen_plan, jload(os.path.join(ART, "prereg_addendum.json")))
    for e in reg["paired_reuse"]:
        fb = next((b for b in fz["blocks"] if b["group"] == e["pairs_with_group"]), None)
        if fb is None or not (fb["start"] <= e["first"] and e["last"] <= fb["end"]):
            raise SeedsError("reuse %s: [%d, %d] is not inside frozen block %s" % (e["id"], e["first"], e["last"], e["pairs_with_group"]))
        for i in e["arms"]:
            a = made[i]
            if not (e["first"] <= a["seeds"]["start"] and a["seeds"]["start"] + a["seeds"]["count"] - 1 <= e["last"]):
                raise SeedsError("reuse %s: arm %s seeds outside [%d, %d]" % (e["id"], i, e["first"], e["last"]))
            if a["runner"] == "par2":
                ts = a["par2"].get("transport_seed")
                fts = root[i]["par2"].get("transport_seed")
                if ts != base or fts != base:
                    raise SeedsError("reuse %s: arm %s transport_seed %s / frozen %s is not the frozen rule base %d" % (e["id"], i, ts, fts, base))
        out.append("PASS reuse %s: %s seeds %d-%d inside frozen block %s [%d, %d]%s" % (
            e["id"], ",".join(e["arms"]), e["first"], e["last"], fb["group"], fb["start"], fb["end"],
            "; transport_seed %d = frozen rule" % base if "Par2" in e["transport"] else ""))
    res = {b["group"]: b["reserves"] if not b.get("reserve_only") else {"start": b["start"], "count": b["count"]} for b in reg["blocks"]}
    for i, a in made.items():   # the plan's groups use exactly the registry's reserves, and every arm's seeds are in a new block or a declared reuse
        pre_r = next(s for s in jload(os.path.join(ART, "prereg_addendum.json"))["arms"] if s["id"] == i)["reserves"]
        if res.get(a["group"]) != pre_r:
            raise SeedsError("arm %s: reserves of group %s are not those of the registry" % (i, a["group"]))
        lo, hi = a["seeds"]["start"], a["seeds"]["start"] + a["seeds"]["count"] - 1
        ok = any(b["start"] <= lo and hi <= b["end"] and not b.get("reserve_only") for b in reg["blocks"]) or any(
            r["first"] <= lo and hi <= r["last"] and i in r["arms"] for r in reg["paired_reuse"])
        if not ok:
            raise SeedsError("arm %s: seeds %d-%d are neither a new block nor a declared reuse" % (i, lo, hi))
    out.append("PASS plan consistency: %d arms, every seed range a new block or a declared reuse, reserves as registered" % len(made))
    return out


def dumps(reg):
    return json.dumps(reg, indent=1) + "\n"
