"""Writes data/cases.txt, the (ny, window, M) cases of the production-code verification (deterministic).

Regenerate the committed probe fixture (needs a build of the seedlattice_probe target), from the scripts root:
    python3 -m seedlattice.make_cases
    build/<preset>/seedlattice_probe docs/experiments/artifacts/2026-10-30-sf42-confirmatory-tooling/scripts/seedlattice/data/cases.txt \
        > docs/experiments/artifacts/2026-10-30-sf42-confirmatory-tooling/scripts/seedlattice/data/probe_output.txt
The ctest `seedlattice_probe` re-runs the probe and compares it with the predictor and with that fixture.
"""
import os
import random

D = "0.1,0.9,0.1,0.9"
W24 = "0.3,0.7,0.3,0.7"
W12 = "0.36666666666666664,0.63333333333333336,0.36666666666666664,0.63333333333333336"  # SF-39 s4_w12
FULL = "0,1,0,1"
DATA = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data")
CASES = os.path.join(DATA, "cases.txt")
FIXTURE = os.path.join(DATA, "probe_output.txt")
GRIDS = (16, 24, 48, 64, 96, 120, 128, 192, 240, 256, 288, 384, 480)


def cases():
    out = [(384, D, 128)]                                                       # known failure (3 | ny, power of two)
    out += [(ny, D, 100) for ny in (256, 384, 64, 128, 192)]                    # SF-39 M = 100 on its grids
    out += [(384, W24, 100), (192, W12, 100), (192, W24, 100)]
    for ny in GRIDS:                                                           # full plane: both sides of v2(M) >= v2(ny)
        out += [(ny, FULL, M) for M in list(range(1, 41)) + [48, 64, 96, 128, 192, 256, 512, 1024]]
    for win in (D, W24):
        for ny in (96, 120, 192, 240, 288, 384, 480):
            out += [(ny, win, M) for M in list(range(1, 25)) + [50, 56, 58, 60, 64, 94, 96, 100, 128, 187, 192, 200, 202, 256]]
    # edges: overflowing width (inf/NaN positions), tiny windows, asymmetric windows
    out += [(16, "-1e308,1e308,0.1,0.9", 4), (16, "0.1,0.9,-1e308,1e308", 4), (16, "-1e308,1e308,-1e308,1e308", 1),
            (96, "0.5,0.5000001,0.5,0.5000001", 7), (96, "0.1,0.9,0.3,0.7", 100), (240, "0.3,0.7,0.1,0.9", 128),
            (384, "0,1,0.1,0.9", 128), (384, "0.1,0.9,0,1", 128), (384, D, 1), (384, D, 4096 // 8)]
    rng = random.Random(20261030)
    for _ in range(400):
        ny = 2 * rng.randint(2, 260)
        win = []
        for _ in range(2):
            a = rng.randint(0, 45) / 100.0
            b = rng.randint(55, 100) / 100.0
            win += [repr(a), repr(b)]
        out.append((ny, ",".join(win), rng.randint(1, 300)))
    return out


def main():
    os.makedirs(DATA, exist_ok=True)
    with open(CASES, "w") as f:
        f.write("# ny window M   (generated by seedlattice.make_cases; do not edit)\n")
        for ny, w, M in cases():
            f.write("%d %s %d\n" % (ny, w, M))


if __name__ == "__main__":
    main()
